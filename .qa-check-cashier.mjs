import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const ctx = await browser.newContext();
const login = await ctx.request.post('http://127.0.0.1:5173/api/auth/login', { data: { identifier:'smoketester', password:'SmokeTest123' }, headers:{'X-Requested-With':'donutcash'} });
console.log('login', login.status());
const page = await ctx.newPage();
page.on('console', m => { if (m.type()==='error') console.log('console', m.text()); });
page.on('response', r => { if (r.url().includes('/api/') && r.status() >= 400) console.log('bad', r.status(), r.url()); });
await page.goto('http://127.0.0.1:5173/cashier', { waitUntil:'networkidle' });
console.log('url', page.url());
console.log('body', (await page.locator('body').innerText()).slice(0,600));
await page.screenshot({ path:'/tmp/cashier-check.png', fullPage:true });
await browser.close();
